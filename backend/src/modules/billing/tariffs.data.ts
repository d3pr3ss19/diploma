function generatedTariff(index: number): RegionTariffs {
  const shift = index + 1;
  const cold = 28 + ((shift * 17) % 23) + (shift % 7) * 0.11;
  const hot = 140 + ((shift * 29) % 95) + (shift % 5) * 0.19;
  const electricity = 3.8 + ((shift * 13) % 44) / 10;

  return {
    COLD_WATER: Number(cold.toFixed(2)),
    HOT_WATER: Number(hot.toFixed(2)),
    ELECTRICITY: Number(electricity.toFixed(2)),
  };
}

export const REGION_TARIFFS: Record<string, RegionTariffs> = RUSSIAN_REGIONS.reduce<Record<string, RegionTariffs>>((acc, region, index) => {
  acc[region] = generatedTariff(index);
  return acc;
}, {});

export const ALL_RUSSIAN_REGIONS = Object.keys(REGION_TARIFFS);
